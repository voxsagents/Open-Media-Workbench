//! Canonical data contracts and structures for the AI Dubbing Timeline.

use std::collections::HashMap;
use std::path::PathBuf;
use std::time::{SystemTime, UNIX_EPOCH};

use serde::{Deserialize, Serialize};
use uuid::Uuid;

/// Current schema version for DubbingProject.
pub const DUBBING_SCHEMA_VERSION: u32 = 1;

/// Overall status of an individual dubbing segment.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum DubbingSegmentStatus {
    /// Audio asset is ready and placed.
    Ready,
    /// Subtitle cue text or voice configuration has changed since synthesis.
    Outdated,
    /// Audio asset file is missing from disk.
    MissingAsset,
    /// Segment overlaps with another segment on the same track.
    Overlapping,
    /// Segment duration significantly exceeds the subtitle cue interval.
    ExceedsCue,
    /// Generation failed or asset is corrupt.
    Error,
}

/// Diagnostic issue codes identifying timeline discrepancies.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum DubbingDiagnosticCode {
    MissingAudioSegment,
    UnresolvedVoiceAssignment,
    VoiceModelUnavailable,
    SourceCueChanged,
    SegmentOverlap,
    SegmentOutsideMedia,
    SegmentExceedsSubtitleInterval,
    LargeDialogueGap,
    InvalidSourceTrim,
    MissingAudioAsset,
    CorruptedAudioAsset,
    LanguageVoiceMismatch,
    DuplicateCueSegment,
}

/// Severity classification for timeline diagnostic findings.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum DiagnosticSeverity {
    Info,
    Warning,
    Error,
}

/// A diagnostic finding reported on the dubbing timeline.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct DubbingDiagnosticFinding {
    pub code: DubbingDiagnosticCode,
    pub severity: DiagnosticSeverity,
    pub track_id: Option<String>,
    pub segment_id: Option<String>,
    pub cue_id: Option<String>,
    pub message: String,
    pub time_range_us: Option<(u64, u64)>,
}

/// Durable, app-managed audio asset generated by TTS and referenced by timeline segments.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct DubbingAudioAsset {
    /// Stable asset UUID.
    pub asset_id: String,
    /// Relative or absolute path to durable audio file (~/.local/share/opentake/audio_assets/dubbing/<id>.wav).
    pub file_path: PathBuf,
    /// Original file name.
    pub file_name: String,
    /// SHA-256 digest of the audio file.
    pub sha256: String,
    /// Sample rate in Hz (e.g. 22,050 Hz).
    pub sample_rate: u32,
    /// Channel count (e.g. 1 for mono).
    pub channel_count: u16,
    /// Total duration in microseconds.
    pub duration_us: u64,
    /// File size in bytes.
    pub size_bytes: u64,
    /// Model voice identifier used to synthesize this asset.
    pub voice_id: String,
    /// Optional speaker variant ID.
    pub speaker_id: Option<u32>,
    /// Creation timestamp (Unix epoch milliseconds).
    pub created_at_epoch_ms: u64,
}

/// A non-destructive clip placed on a dubbing track.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct DubbingSegment {
    /// Stable segment UUID.
    pub id: String,
    /// Track UUID containing this segment.
    pub track_id: String,
    /// Linked subtitle cue UUID.
    pub source_subtitle_cue_id: Option<String>,
    /// Linked subtitle track UUID.
    pub source_subtitle_track_id: Option<String>,
    /// Subtitle cue dialogue text synthesized for this segment.
    pub source_text: String,
    /// SHA-256 digest of source text to detect cue modifications.
    pub source_text_hash: String,
    /// Model voice identifier.
    pub voice_id: String,
    /// Optional speaker variant ID.
    pub speaker_id: Option<u32>,
    /// Reference to underlying durable audio asset.
    pub audio_asset_id: String,
    /// Trim in-point relative to audio asset start (microseconds).
    pub source_in_us: u64,
    /// Trim out-point relative to audio asset start (microseconds).
    pub source_out_us: u64,
    /// Position on the dubbing timeline where playback starts (microseconds).
    pub timeline_start_us: u64,
    /// Original subtitle cue start time (microseconds).
    pub original_cue_start_us: Option<u64>,
    /// Original subtitle cue end time (microseconds).
    pub original_cue_end_us: Option<u64>,
    /// Linear playback gain [0.0 - 2.0].
    pub gain: f32,
    /// Visual and operational status.
    pub status: DubbingSegmentStatus,
    /// Non-fatal diagnostic warning messages.
    #[serde(default)]
    pub warnings: Vec<String>,
    /// Original TTS audio asset ID (before duration alignment).
    #[serde(default)]
    pub original_audio_asset_id: Option<String>,
    /// Aligned audio asset ID (if tempo/padding alignment has been processed).
    #[serde(default)]
    pub aligned_audio_asset_id: Option<String>,
    /// Active alignment mode (Original, AutoFit, TempoAdjust, PadSilence, Manual).
    #[serde(default)]
    pub alignment_mode:
        Option<crate::localization::dubbing::alignment::models::DubbingAlignmentMode>,
    /// Planned duration alignment parameters.
    #[serde(default)]
    pub alignment_plan:
        Option<crate::localization::dubbing::alignment::models::DubbingAlignmentPlan>,
    /// Processed duration alignment execution results.
    #[serde(default)]
    pub alignment_result:
        Option<crate::localization::dubbing::alignment::models::DubbingAlignmentResult>,
    /// Manual start offset in microseconds relative to cue start.
    #[serde(default)]
    pub start_offset_us: Option<i64>,
}

impl DubbingSegment {
    /// Returns the active trimmed duration of this segment in microseconds.
    #[inline]
    pub fn trimmed_duration_us(&self) -> u64 {
        self.source_out_us.saturating_sub(self.source_in_us)
    }

    /// Returns the effective end position of this segment on the timeline.
    #[inline]
    pub fn timeline_end_us(&self) -> u64 {
        self.timeline_start_us
            .saturating_add(self.trimmed_duration_us())
    }

    /// Evaluates overrun relative to original subtitle cue end time.
    /// Positive values indicate speech extends beyond subtitle display interval.
    #[inline]
    pub fn cue_overrun_us(&self) -> Option<i64> {
        self.original_cue_end_us
            .map(|cue_end| (self.timeline_end_us() as i64) - (cue_end as i64))
    }

    /// Returns the currently active audio asset ID for playback and waveform rendering.
    pub fn active_audio_asset_id(&self) -> &str {
        if let Some(
            crate::localization::dubbing::alignment::models::DubbingAlignmentMode::Original,
        ) = self.alignment_mode
        {
            self.original_audio_asset_id
                .as_deref()
                .unwrap_or(&self.audio_asset_id)
        } else if let Some(aligned_id) = &self.aligned_audio_asset_id {
            aligned_id.as_str()
        } else {
            &self.audio_asset_id
        }
    }

    /// Returns whether this segment currently has an active aligned asset applied.
    pub fn is_aligned(&self) -> bool {
        self.aligned_audio_asset_id.is_some()
            && self.alignment_mode
                != Some(
                    crate::localization::dubbing::alignment::models::DubbingAlignmentMode::Original,
                )
    }
}

/// A dedicated audio track in the dubbing timeline.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct DubbingTrack {
    /// Stable track UUID.
    pub id: String,
    /// Track display name (e.g. "English Dubbing", "Dialogue A").
    pub display_name: String,
    /// ISO 639-1 language code (e.g. "en", "es", "bn").
    pub language: String,
    /// Subtitle track ID from which this dubbing track was constructed.
    pub source_subtitle_track_id: Option<String>,
    /// Assigned default voice model ID.
    pub assigned_voice_id: Option<String>,
    /// Assigned speaker variant ID.
    pub assigned_speaker_id: Option<u32>,
    /// Chronologically ordered audio segments.
    pub segments: Vec<DubbingSegment>,
    /// Mute state during timeline preview.
    pub is_muted: bool,
    /// Solo state during timeline preview.
    pub is_solo: bool,
    /// Enabled state for export and processing.
    pub is_enabled: bool,
}

impl DubbingTrack {
    pub fn new(
        id: impl Into<String>,
        display_name: impl Into<String>,
        language: impl Into<String>,
    ) -> Self {
        Self {
            id: id.into(),
            display_name: display_name.into(),
            language: language.into(),
            source_subtitle_track_id: None,
            assigned_voice_id: None,
            assigned_speaker_id: None,
            segments: Vec::new(),
            is_muted: false,
            is_solo: false,
            is_enabled: true,
        }
    }

    /// Sorts all segments chronologically by timeline start position.
    pub fn sort_segments(&mut self) {
        self.segments.sort_by(|a, b| {
            a.timeline_start_us
                .cmp(&b.timeline_start_us)
                .then_with(|| a.timeline_end_us().cmp(&b.timeline_end_us()))
        });
    }

    /// Returns the maximum timeline end position among all segments on this track.
    pub fn duration_us(&self) -> u64 {
        self.segments
            .iter()
            .map(|s| s.timeline_end_us())
            .max()
            .unwrap_or(0)
    }
}

/// Canonical root project container for the AI Dubbing Timeline.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct DubbingProject {
    /// Format schema version.
    pub schema_version: u32,
    /// Stable dubbing project UUID.
    pub id: String,
    /// Associated SubtitleDocument UUID.
    pub source_project_id: String,
    /// Associated MediaAsset ID (video/audio).
    pub media_reference: Option<String>,
    /// Timeline duration in microseconds (derived from video or segments).
    pub timeline_duration_us: u64,
    /// Source dialogue language (e.g. "en").
    pub source_language: String,
    /// Target dubbing language (e.g. "es").
    pub target_language: String,
    /// Dubbing tracks.
    pub tracks: Vec<DubbingTrack>,
    /// Manifest of durable audio assets referenced by segments.
    #[serde(default)]
    pub assets: HashMap<String, DubbingAudioAsset>,
    /// Creation timestamp (Unix epoch milliseconds).
    pub created_at_epoch_ms: u64,
    /// Last update timestamp (Unix epoch milliseconds).
    pub updated_at_epoch_ms: u64,
}

impl DubbingProject {
    pub fn new(
        source_project_id: impl Into<String>,
        source_language: impl Into<String>,
        target_language: impl Into<String>,
        media_reference: Option<String>,
    ) -> Self {
        let now_ms = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map(|d| d.as_millis() as u64)
            .unwrap_or(0);

        Self {
            schema_version: DUBBING_SCHEMA_VERSION,
            id: Uuid::new_v4().to_string(),
            source_project_id: source_project_id.into(),
            media_reference,
            timeline_duration_us: 0,
            source_language: source_language.into(),
            target_language: target_language.into(),
            tracks: Vec::new(),
            assets: HashMap::new(),
            created_at_epoch_ms: now_ms,
            updated_at_epoch_ms: now_ms,
        }
    }

    /// Updates the modification timestamp.
    pub fn touch(&mut self) {
        self.updated_at_epoch_ms = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map(|d| d.as_millis() as u64)
            .unwrap_or(0);
    }

    /// Finds a track by its UUID.
    pub fn find_track(&self, track_id: &str) -> Option<&DubbingTrack> {
        self.tracks.iter().find(|t| t.id == track_id)
    }

    /// Finds a mutable track by its UUID.
    pub fn find_track_mut(&mut self, track_id: &str) -> Option<&mut DubbingTrack> {
        self.tracks.iter_mut().find(|t| t.id == track_id)
    }

    /// Finds a segment and its containing track by segment UUID.
    pub fn find_segment(&self, segment_id: &str) -> Option<(&DubbingTrack, &DubbingSegment)> {
        for track in &self.tracks {
            if let Some(segment) = track.segments.iter().find(|s| s.id == segment_id) {
                return Some((track, segment));
            }
        }
        None
    }

    /// Finds a mutable segment by segment UUID.
    pub fn find_segment_mut(&mut self, segment_id: &str) -> Option<&mut DubbingSegment> {
        for track in &mut self.tracks {
            if let Some(segment) = track.segments.iter_mut().find(|s| s.id == segment_id) {
                return Some(segment);
            }
        }
        None
    }
}

/// A normalized waveform bin for fast timeline audio visualization.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct DubbingWaveformBin {
    /// Normalized minimum peak in [-1.0, 1.0].
    pub min: f32,
    /// Normalized maximum peak in [-1.0, 1.0].
    pub max: f32,
    /// Normalized RMS amplitude in [0.0, 1.0].
    pub rms: f32,
}

/// Full waveform peak summary for an audio asset or segment.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct DubbingTimelineWaveform {
    pub segment_id: String,
    pub asset_id: String,
    pub sample_rate: u32,
    pub duration_us: u64,
    pub bins: Vec<DubbingWaveformBin>,
}
